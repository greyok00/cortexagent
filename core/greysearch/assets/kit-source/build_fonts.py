import os
import re
import sys
import urllib.request
HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, 'fonts')
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36'
FAMILIES = [('Barlow Condensed', ['500', '600', '700'], False), ('Source Serif 4', ['400', '600', '700'], False), ('Source Serif 4', ['400'], True), ('IBM Plex Mono', ['400', '500', '600'], False), ('Inter', ['400', '600', '700'], False), ('Space Grotesk', ['500', '600', '700'], False), ('JetBrains Mono', ['400', '500', '700'], False)]
def css_url(fam, weights, italic):
    name = fam.replace(' ', '+')
    if italic:
        return f'https://fonts.googleapis.com/css2?family={name}:ital,wght@1,' + ';'.join(weights) + '&display=swap'
    return f'https://fonts.googleapis.com/css2?family={name}:wght@' + ';'.join(weights) + '&display=swap'
def get(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')
def main():
    os.makedirs(FONTS, exist_ok=True)
    blocks, seen = ([], set())
    for fam, weights, italic in FAMILIES:
        css = get(css_url(fam, weights, italic))
        for m in re.finditer('/\\*\\s*([\\w\\-\\[\\]]+)\\s*\\*/\\s*(@font-face\\s*\\{.*?\\})', css, re.S):
            subset, block = (m.group(1), m.group(2))
            if subset not in ('latin', 'latin-ext'):
                continue
            u = re.search('url\\((https://[^)]+\\.woff2)\\)', block)
            if not u:
                continue
            url = u.group(1)
            fname = re.sub('[^A-Za-z0-9]+', '-', f"{fam}-{subset}-{url.rsplit('/', 1)[-1]}")
            if fname not in seen:
                seen.add(fname)
                path = os.path.join(FONTS, fname)
                if not os.path.exists(path):
                    open(path, 'wb').write(get(url, binary=True))
                    print(f'  fetched {fname}')
                else:
                    print(f'  have    {fname}')
            blocks.append(re.sub('url\\(https://[^)]+\\.woff2\\)', f'url(fonts/{fname})', block))
    css_out = '/* Generated by build_fonts.py — do not hand-edit. Relative urls, so the\n   page works from file:// or any local server with no network at all. */\n' + '\n'.join(sorted(set(blocks), key=lambda b: (b.count('italic'), b)))
    open(os.path.join(HERE, 'fonts.css'), 'w', encoding='utf-8').write(css_out)
    total = sum((os.path.getsize(os.path.join(FONTS, f)) for f in os.listdir(FONTS)))
    print(f'\n{len(os.listdir(FONTS))} font files, {total / 1024:.0f} KB total')
    print(f"wrote {os.path.join(HERE, 'fonts.css')}")
    return 0
if __name__ == '__main__':
    sys.exit(main())
