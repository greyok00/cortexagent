#!/usr/bin/env python3
"""build_fonts.py — fetch the typefaces the kit uses, once, and self-host them.

Why self-host instead of the <link> to fonts.googleapis.com that the reference page used:
every site in this kit promises to be an offline local mirror with no outbound requests.
A webfont link is an outbound request on every page load — it tells a third party which
page you opened and when — so the look and the promise cannot both hold unless the files
come here. This runs once; after it, nothing in the kit touches the network.

Output:
    fonts/*.woff2      the files themselves
    fonts.css          @font-face rules with RELATIVE urls, ready to paste into a page

Run:  python3 build_fonts.py
"""
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, 'fonts')

# A Chrome UA is required: the css2 endpoint serves woff2 only to browsers it recognises
# and silently hands everyone else legacy ttf, which would triple the size.
UA = ('Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) '
      'Chrome/126.0.0.0 Safari/537.36')

# (family, weights, italics) — only what the kit actually renders, so nothing is shipped
# unused. Barlow Condensed / Source Serif 4 / IBM Plex Mono are the reference page's three
# faces. Inter / Space Grotesk / JetBrains Mono are the ui-framework's own token families,
# so a theme switch has real faces to switch to rather than a fallback.
FAMILIES = [
    ('Barlow Condensed', ['500', '600', '700'], False),
    ('Source Serif 4', ['400', '600', '700'], False),
    ('Source Serif 4', ['400'], True),
    ('IBM Plex Mono', ['400', '500', '600'], False),
    ('Inter', ['400', '600', '700'], False),
    ('Space Grotesk', ['500', '600', '700'], False),
    ('JetBrains Mono', ['400', '500', '700'], False),
]


def css_url(fam, weights, italic):
    name = fam.replace(' ', '+')
    if italic:
        return (f'https://fonts.googleapis.com/css2?family={name}:ital,wght@1,'
                + ';'.join(weights) + '&display=swap')
    return (f'https://fonts.googleapis.com/css2?family={name}:wght@'
            + ';'.join(weights) + '&display=swap')


def get(url, binary=False):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else data.decode('utf-8')


def main():
    os.makedirs(FONTS, exist_ok=True)
    blocks, seen = [], set()
    for fam, weights, italic in FAMILIES:
        css = get(css_url(fam, weights, italic))
        # The API returns one @font-face per weight per subset. Keep only latin and
        # latin-ext: the study is US/Arizona English, and the other subsets were 60% of
        # the bytes for faces a reader here will never need.
        for m in re.finditer(r'/\*\s*([\w\-\[\]]+)\s*\*/\s*(@font-face\s*\{.*?\})', css, re.S):
            subset, block = m.group(1), m.group(2)
            if subset not in ('latin', 'latin-ext'):
                continue
            u = re.search(r'url\((https://[^)]+\.woff2)\)', block)
            if not u:
                continue
            url = u.group(1)
            fname = re.sub(r'[^A-Za-z0-9]+', '-', f'{fam}-{subset}-{url.rsplit("/", 1)[-1]}')
            if fname not in seen:
                seen.add(fname)
                path = os.path.join(FONTS, fname)
                if not os.path.exists(path):
                    open(path, 'wb').write(get(url, binary=True))
                    print(f'  fetched {fname}')
                else:
                    print(f'  have    {fname}')
            blocks.append(re.sub(r'url\(https://[^)]+\.woff2\)', f'url(fonts/{fname})', block))

    # One rule per face, sorted so a diff of this file is readable.
    css_out = ('/* Generated by build_fonts.py — do not hand-edit. Relative urls, so the\n'
               '   page works from file:// or any local server with no network at all. */\n'
               + '\n'.join(sorted(set(blocks), key=lambda b: (b.count('italic'), b))))
    open(os.path.join(HERE, 'fonts.css'), 'w', encoding='utf-8').write(css_out)
    total = sum(os.path.getsize(os.path.join(FONTS, f)) for f in os.listdir(FONTS))
    print(f'\n{len(os.listdir(FONTS))} font files, {total/1024:.0f} KB total')
    print(f'wrote {os.path.join(HERE, "fonts.css")}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
