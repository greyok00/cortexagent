interface McpServerConn {
	server: string;
	proc: childProcess.ChildProcess;
	nextId: number;
	pending: Map<number, { resolve: (v: unknown) => void; reject: (e: Error) => void }>;
	buffer: string;
	tools: { name: string; description?: string; inputSchema?: Record<string, unknown> }[];
}

function logLine(m: string): void {
	try {
		fs.appendFileSync("/tmp/mcp_client.log", new Date().toISOString() + " [locked] " + m + "\n");
	} catch {}
}

function lanePins(): Record<string, string> {
	try {
		const parsed = JSON.parse(fs.readFileSync(PINS_PATH, "utf8")) as LanePins;
		return parsed.pins ?? {};
	} catch {
		logLine("lane-pins.json MISSING — locked lane refuses to spawn; run scripts/gen_lane_pins.py");
		return {};
	}
}

function verifyPins(entry: LockedServer): boolean {
	const pins = lanePins();
	if (!Object.keys(pins).length) {
		logLine("NO lane pins available — refusing to spawn " + entry.name);
		return false;
	}
	for (const rel of entry.pins) {
		const abs = path.join(ROOT, rel);
		const got = (() => {
			try {
				return crypto.createHash("sha256").update(fs.readFileSync(abs)).digest("hex");
			} catch {
				logLine(`PIN MISSING ${rel} — refusing to spawn ${entry.name}`);
				return "";
			}
		})();
		if (got !== pins[rel]) {
			logLine(`PIN MISMATCH ${rel}: wanted ${pins[rel]} got ${got} — refusing to spawn ${entry.name}`);
			return false;
		}
	}
	return true;
}

function spawnServer(entry: LockedServer): McpServerConn | null {
	const proc = childProcess.spawn("/bin/sh", ["-c", entry.command], {
		cwd: ROOT,
		stdio: ["pipe", "pipe", "pipe"],
	});
	const conn: McpServerConn = {
		server: entry.name,
		proc,
		nextId: 1,
		pending: new Map(),
		buffer: "",
		tools: [],
	};
	proc.stdout!.on("data", (chunk: Buffer) => {
		conn.buffer += chunk.toString();
		let nl: number;
		while ((nl = conn.buffer.indexOf("\n")) !== -1) {
			const line = conn.buffer.slice(0, nl).trim();
			conn.buffer = conn.buffer.slice(nl + 1);
			if (!line) continue;
			try {
				const msg = JSON.parse(line);
				const id = msg.id as number | undefined;
				if (id !== undefined && conn.pending.has(id)) {
					const p = conn.pending.get(id)!;
					conn.pending.delete(id);
					if (msg.error) p.reject(new Error(String(msg.error.message ?? JSON.stringify(msg.error))));
					else p.resolve(msg.result);
				}
			} catch {
				/* non-JSON line — servers may log; ignore */
			}
		}
	});
	proc.stderr?.on("data", () => undefined);
	proc.on("exit", () => {
		for (const [, p] of conn.pending) {
			try { p.reject(new Error(`${entry.name}: server process exited`)); } catch {}
		}
		conn.pending.clear();
	});
	return conn;
}

function call(conn: McpServerConn, method: string, params: unknown, timeoutMs?: number): Promise<unknown> {
	const id = conn.nextId++;
	const body = JSON.stringify({ jsonrpc: "2.0", id, method, params }) + "\n";
	return new Promise((resolve, reject) => {
		const timer = setTimeout(() => {
			conn.pending.delete(id);
			reject(new Error(`${conn.server}: ${method} timed out`));
		}, timeoutMs);
		conn.pending.set(id, {
			resolve: (v) => { clearTimeout(timer); resolve(v); },
			reject: (e: Error) => { clearTimeout(timer); reject(e); },
		});
		conn.proc.stdin!.write(body, (err: Error | null | undefined) => {
			if (err) {
				for (const [, p] of conn.pending) {
					try { p.reject(new Error(`${conn.server}: request write failed: ${err.message}`)); } catch {}
				}
				conn.pending.clear();
			}
		});
	});
}

async function handshake(entry: LockedServer, conn: McpServerConn): Promise<void> {
	await call(conn, "initialize", {
		protocolVersion: "2024-11-05",
		capabilities: {},
		clientInfo: { name: "cortex-agent", version: "0.7.5.1" },
	}, 15000);
	conn.proc.stdin!.write(JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" }) + "\n");
	const listed = (await call(conn, "tools/list", {}, 15000)) as
		{ tools?: { name: string; description?: string; inputSchema?: Record<string, unknown> }[] };
	logLine(entry.name + " tools=" + (listed.tools ?? []).map((t) => t.name).join(","));
	conn.tools = listed.tools ?? [];
}

function textOf(result: unknown): string {
	const r = result as { content?: { type?: string; text?: string }[]; isError?: boolean } | null;
	if (!r || !Array.isArray(r.content)) return JSON.stringify(result ?? null);
	return r.content
		.map((c) => (c.type === "text" ? String(c.text ?? "") : JSON.stringify(c)))
		.join("\n");
}

export default function lockedMcp(pi: ExtensionAPI): void {
	logLine("locked lane: " + LOCKED_SERVERS.map((s) => s.name).join(","));
	for (const entry of LOCKED_SERVERS) {
		if (!verifyPins(entry)) {
			// A vendored source failed its pin. Register a single refusing
			// probe tool so the model surfaces the breakage honestly instead
			// of silently missing its core capabilities.
			pi.registerTool({
				name: `mcp_${entry.name}_locked`,
				label: `mcp_${entry.name}_locked`,
				description: `[LOCKED-BROKEN] ${entry.name}: vendored source failed its sha256 pin — report this to the operator; do not guess around it.`,
				parameters: { type: "object", properties: {} } as never,
				prepareArguments: (args) => args as never,
				execute: async () => ({
					content: [{ type: "text", text: `${entry.name}: LOCKED SOURCE PIN FAILED — the vendored copy was modified or is missing. Escalate to the operator.` }],
				}),
			});
			continue;
		}
		void (async () => {
			// 2026-11-10: spawn with retries — a transient spawn failure must
			// not cost a session its core capabilities (the anti-self-disable
			// rule; the sleep lives here because this is an async context).
			let conn: McpServerConn | null = null;
			for (let attempt = 1; attempt <= 3; attempt++) {
				try {
					const spawned = spawnServer(entry);
					if (!spawned) return; // /bin/sh failed to start at all
					conn = spawned;
					logLine("locked-spawn " + entry.name + " pid=" + (conn.proc.pid ?? null) + " attempt=" + attempt);
					break;
				} catch (e) {
					logLine("locked spawn error attempt " + attempt + ": " + String(e));
					if (attempt < 3) await new Promise<void>((r) => setTimeout(r, 2000 * attempt));
				}
			}
			if (!conn) return;
			try {
				await handshake(entry, conn);
				for (const t of conn.tools) {
					const toolName = `mcp_${entry.name}_${t.name}`;
					pi.registerTool({
						name: toolName,
						label: toolName,
						description: `[${entry.name} MCP — 🔒 locked, always on] ${t.description ?? t.name}`,
						parameters: (t.inputSchema ?? { type: "object", properties: {} }) as never,
						prepareArguments: (args) => args as never,
						execute: async (_id, params) => {
							if (conn.proc.exitCode !== null) {
								try { conn.proc.kill(); } catch {}
								if (!verifyPins(entry)) {
									return { content: [{ type: "text", text: `${entry.name}: respawn refused — vendored source failed its pin` }] };
								}
								const fresh = spawnServer(entry);
								if (!fresh) {
									return { content: [{ type: "text", text: `${entry.name}: server process died and could not be respawned` }] };
								}
								Object.assign(conn, fresh);
								await handshake(entry, conn);
							}
							const res = await call(conn, "tools/call", { name: t.name, arguments: params ?? {} }, entry.callTimeoutMs);
							return {
								content: [{ type: "text", text: textOf(res) }],
								details: { server: entry.name, tool: t.name },
							};
						},
					});
				}
			} catch (e) {
				logLine("locked handshake error " + String(e));
			}
		})();
	}
}
