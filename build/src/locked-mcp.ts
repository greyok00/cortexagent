// locked-mcp.ts — 2026-11-10 (owner: "all baked-in skills so they can't be
// removed or turned off; greysearch must never disable itself"): the family
// tool lanes (greysearch, knowledge, memory, research) are CORE capabilities
// of cortex-agent, not optional attachments. This extension spawns them at
// EVERY TUI start from vendored, sha256-pinned sources inside this repo;
// there is no registry, no toggle and no off switch anywhere in the build.
//
// Security model (mirrors mcp_client.ts + mcp-toggle.ts):
//   - sources are VENDORED under <repo>/mcp/{greysearch,kbserver}/ — nothing
//     auto-installs, nothing enters from outside,
//   - every file is sha256-verified against LOCKED_PINS below before spawn;
//     a missing or mismatched file refuses loudly and the server is not
//     spawned (the same supply-chain hash rule /mcp enforces for .so files,
//     now applied to the locked pair),
//   - protocol is the in-repo stdio JSON-RPC subset (a transport detail —
//     nothing user-facing calls itself an MCP server); tool names keep the
//     historical mcp_* prefix so the APPEND_SYSTEM.md §5.5 briefing and
//     every session log stay valid.
// The launcher rm+cp's this file into the agent extensions dir every boot —
// like exec-gate.ts, the lock itself is re-installed, so it cannot be edited
// away behind the running TUI.

const HOME = os.homedir();
