#!/usr/bin/env python3
"""Generate MANIFEST.json — the source-of-truth inventory of the frozen tree.

Small files get sha256 (checked every boot); heavy files (models, wheels)
are pinned by exact size only (hashing 13+ GB would slow every boot) and can
be hash-checked with --full. Regenerate after ANY artifact change, then run
bin/verify_compiled.py — a boot must never carry a stale manifest.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAX_HASH_BYTES = 64 * 1024 * 1024  # hash everything below this; size-pin above

WALK_DIRS = ["mcp",
             "core", "tools", "services", "build/src", "vendor/slimtoken/src/slimtoken",
             "vendor/engine",
             "tui/packages/agent/dist", "tui/packages/ai/dist", "tui/packages/client/dist",
             "tui/packages/coding-agent/dist", "tui/packages/protocol/dist", "tui/packages/server/dist",
             "tui/packages/session-backends/sqlite-node/dist"]


def _sha256(p: Path, chunk: int = 1024 * 1024) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def _derived(p: Path) -> bool:
    """Derived/generated artifacts are not frozen pins: cython .c intermediates,
    scratch build dirs, object files, caches."""
    rel = str(p).replace("\\", "/")
    if p.suffix in {".o", ".c"}:
        return True
    return any(part in {"__pycache__", "build"} for part in p.parts)


# Runtime-mutable state is written by the server while it runs, so pinning its
# exact size/hash makes every boot fail after the first write (owner incident
# 2026-10-27: engine-status.json drifted 794->790 and the boot gate refused to
# start). These are live state, not build artifacts — never frozen.
RUNTIME_NAMES = {"engine-status.json", "task-registry.json", "tuning.json"}
RUNTIME_DIRS = {"guides", "photo-cache"}


def _runtime(p: Path) -> bool:
    if p.name == "lane-pins.json":  # boot-regenerated by gen_lane_pins.py — never pinned
        return True
    rel = p.relative_to(ROOT)
    return p.name in RUNTIME_NAMES or any(part in RUNTIME_DIRS for part in rel.parts)


def main() -> int:
    out = {}
    for d in WALK_DIRS:
        base = ROOT / d
        if not base.exists():
            out[d] = {"error": "MISSING DIRECTORY"}
            continue
        for p in sorted(base.rglob("*")):
            if not p.is_file() or _derived(p) or _runtime(p):
                continue
            rel = str(p.relative_to(ROOT))
            try:
                size = p.stat().st_size
            except OSError:
                continue
            if size > MAX_HASH_BYTES:
                out[rel] = {"size": size}
            else:
                out[rel] = {"size": size, "sha256": _sha256(p)}
    manifest = {
        "name": "cortexagent-hardened",
        "format": 1,
        "hashed_below": MAX_HASH_BYTES,
        "files": out,
    }
    path = ROOT / "state" / "MANIFEST.json"
    path.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    print(f"MANIFEST: {len(out)} files -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())